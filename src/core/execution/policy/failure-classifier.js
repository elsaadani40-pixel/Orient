const FAILURE_CLASSES = Object.freeze({
  TRANSIENT: 'transient',
  DETERMINISTIC: 'deterministic',
  AUTHORIZATION: 'authorization',
  VALIDATION: 'validation',
  DEPENDENCY: 'dependency',
  EXTERNAL: 'external',
  RESOURCE: 'resource',
  UNKNOWN: 'unknown'
});

const CLASS_BY_CODE = Object.freeze({
  TIMEOUT: FAILURE_CLASSES.TRANSIENT,
  TEMPORARY_FAILURE: FAILURE_CLASSES.TRANSIENT,
  RATE_LIMITED: FAILURE_CLASSES.TRANSIENT,
  SERVICE_UNAVAILABLE: FAILURE_CLASSES.EXTERNAL,
  NETWORK_ERROR: FAILURE_CLASSES.EXTERNAL,
  UPSTREAM_FAILURE: FAILURE_CLASSES.EXTERNAL,
  DEPENDENCY_UNAVAILABLE: FAILURE_CLASSES.DEPENDENCY,
  AUTHORIZATION_FAILED: FAILURE_CLASSES.AUTHORIZATION,
  TOOL_NOT_AUTHORIZED: FAILURE_CLASSES.AUTHORIZATION,
  APPROVAL_CONSUME_FAILED: FAILURE_CLASSES.AUTHORIZATION,
  INVALID_INPUT: FAILURE_CLASSES.VALIDATION,
  INVALID_PLAN: FAILURE_CLASSES.VALIDATION,
  INVALID_PLAN_VALIDATION: FAILURE_CLASSES.VALIDATION,
  TOOL_INPUT_TOO_LARGE: FAILURE_CLASSES.VALIDATION,
  TOOL_NOT_REGISTERED: FAILURE_CLASSES.DETERMINISTIC,
  TOOL_ALREADY_REGISTERED: FAILURE_CLASSES.DETERMINISTIC,
  IDEMPOTENCY_REPLAY_REJECTED: FAILURE_CLASSES.DETERMINISTIC,
  IDEMPOTENCY_OPERATION_UNKNOWN: FAILURE_CLASSES.DEPENDENCY,
  MAX_EXECUTION_TIME_EXCEEDED: FAILURE_CLASSES.RESOURCE,
  MAX_EXECUTION_STEPS_EXCEEDED: FAILURE_CLASSES.RESOURCE,
  RESOURCE_EXHAUSTED: FAILURE_CLASSES.RESOURCE
});

function classifyFailure(error) {
  if (!error) return FAILURE_CLASSES.UNKNOWN;
  if (CLASS_BY_CODE[error.code]) return CLASS_BY_CODE[error.code];
  if (Number(error.status) === 401 || Number(error.status) === 403) {
    return FAILURE_CLASSES.AUTHORIZATION;
  }
  if (Number(error.status) === 400 || Number(error.status) === 409 || Number(error.status) === 422) {
    return FAILURE_CLASSES.VALIDATION;
  }
  if (Number(error.status) === 408 || Number(error.status) === 429 || Number(error.status) >= 500) {
    return Number(error.status) === 429 || Number(error.status) === 408
      ? FAILURE_CLASSES.TRANSIENT
      : FAILURE_CLASSES.EXTERNAL;
  }
  return FAILURE_CLASSES.UNKNOWN;
}

class FailureClassifier {
  classify(error) {
    return classifyFailure(error);
  }
}

FailureClassifier.FAILURE_CLASSES = FAILURE_CLASSES;
FailureClassifier.classify = classifyFailure;
FailureClassifier.FAILURE_CLASSES = FAILURE_CLASSES;

module.exports = FailureClassifier;
